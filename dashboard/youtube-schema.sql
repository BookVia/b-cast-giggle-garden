CREATE TABLE IF NOT EXISTS oauth_states(state TEXT PRIMARY KEY,payload TEXT NOT NULL,expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS youtube_cache(id INTEGER PRIMARY KEY,payload TEXT NOT NULL,updated INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS asset_reviews(id TEXT PRIMARY KEY,asset TEXT NOT NULL,note TEXT NOT NULL,created INTEGER NOT NULL);
